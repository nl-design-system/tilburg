const navButton = (label: string, paths: string[]) =>
  `<button type="button" class="utrecht-button utrecht-button--subtle utrecht-calendar__button" aria-label="${label}">${icon(paths)}</button>`;

const iso = (d: Date) =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
const fmt = (d: Date, options: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat('nl-NL', options).format(d);

interface CalendarHtmlOptions {
  id: string;
  /** Any day in the month shown. */
  month: string;
  today: string;
  selected?: string;
  min?: string;
  max?: string;
}

/** The static reference DOM for one month. */
const calendarHtml = ({ id, month, today, selected, min, max }: CalendarHtmlOptions): string => {
  const [y, m] = month.split('-').map(Number);
  const first = new Date(y, m - 1, 1);
  const start = new Date(y, m - 1, 1 - ((first.getDay() + 6) % 7));
  const days = Array.from(
    { length: 42 },
    (_, i) => new Date(start.getFullYear(), start.getMonth(), start.getDate() + i),
  );
  let tabStop = selected ?? today;
  if (min && tabStop < min) tabStop = min;
  if (max && tabStop > max) tabStop = max;
  const head = days
    .slice(0, 7)
    .map(
      (d) =>
        `<th class="utrecht-calendar__table-weeks-item" scope="col" abbr="${fmt(d, { weekday: 'long' })}">${fmt(d, { weekday: 'short' })}</th>`,
    )
    .join('\n          ');
  const cell = (d: Date) => {
    const value = iso(d);
    const classes = [
      'utrecht-button utrecht-button--subtle utrecht-calendar__button utrecht-calendar__table-days-item-day',
      d.getMonth() !== m - 1 && 'utrecht-calendar__table-days-item-day--out-of-the-month',
      value === today && 'utrecht-calendar__table-days-item-day--is-today',
      value === selected && 'utrecht-calendar__table-days-item-day--selected',
    ]
      .filter(Boolean)
      .join(' ');
    const disabled = (min && value < min) || (max && value > max);
    const label = fmt(d, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' });
    return `<td${value === selected ? ' aria-selected="true"' : ''}><button type="button" class="${classes}" tabindex="${value === tabStop ? 0 : -1}" aria-label="${label}"${value === selected ? ' aria-pressed="true"' : ''}${value === today ? ' aria-current="date"' : ''}${disabled ? ' disabled' : ''}>${d.getDate()}</button></td>`;
  };
  const rows = Array.from(
    { length: 6 },
    (_, w) =>
      `<tr>\n          ${days
        .slice(w * 7, w * 7 + 7)
        .map(cell)
        .join('\n          ')}\n        </tr>`,
  ).join('\n        ');
  return `<div class="utrecht-calendar">
  <div class="utrecht-calendar__navigation">
    <div class="utrecht-calendar__navigation-buttons">
      ${navButton('Vorig jaar', calendarIcons.previousYear)}
      <div class="utrecht-calendar__navigation-buttons">
        ${navButton('Vorige maand', calendarIcons.previousMonth)}
        <time class="utrecht-calendar__navigation-label" id="${id}" datetime="${month.slice(0, 7)}" aria-live="polite">${fmt(first, { month: 'long', year: 'numeric' })}</time>
        ${navButton('Volgende maand', calendarIcons.nextMonth)}
      </div>
      ${navButton('Volgend jaar', calendarIcons.nextYear)}
    </div>
  </div>
  <table class="utrecht-calendar__table" role="grid" aria-labelledby="${id}">
    <thead class="utrecht-calendar__table-weeks-container">
      <tr class="utrecht-calendar__table-weeks-container-content">
          ${head}
      </tr>
    </thead>
    <tbody class="utrecht-calendar__table-days-container">
        ${rows}
    </tbody>
  </table>
</div>`;
};

