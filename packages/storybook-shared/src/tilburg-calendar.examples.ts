/* Canonical HTML/CSS reference markup for the Tilburg calendar. Imported by both the React storybook
   (`packages/storybook`) and the Angular storybook (`packages/storybook-angular`) so the HTML lives in one place.

   The month grid is 42 buttons, so the examples are generated by `calendarHtml()` below instead of written out by
   hand. It produces exactly the DOM the React, Angular and Web Component calendars render; the snapshot is static
   (fixed "today", no keyboard handling). */

