const intro = `Month calendar for picking one date, on the Utrecht \`utrecht-calendar\` classes. Dutch by default: weeks start on Monday, month and day names come from \`Intl\` (\`locale\`, default \`'nl-NL'\`). Buttons step a year or a month back or forward; days outside \`min\` / \`max\` are disabled. Dates go in and out as ISO strings (\`YYYY-MM-DD\`), like \`<input type="date">\`.

**Keyboard** (WAI-ARIA date grid): one day is in the tab order. Arrow keys move a day or a week, Home / End go to Monday / Sunday, Page Up / Page Down a month, Shift + Page Up / Page Down a year; Enter or Space selects. The month label is a polite live region, so a month change is announced.`;

