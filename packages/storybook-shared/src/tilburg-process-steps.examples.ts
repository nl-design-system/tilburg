const intro = `Shows where a request or case stands: an ordered list of steps, each \`checked\` (done), \`current\` or \`not-checked\` (still to come), optionally with a line of extra text (\`meta\`), a date and sub-steps. Markup and CSS are the Den Haag process steps that Utrecht's \`process-steps\` component refers to (\`denhaag-process-steps\` and \`denhaag-step-marker\` classes). Not taken over from Den Haag: collapsible steps (the header toggle button) and the warning / error / disabled statuses; every step and sub-step is always shown.

Accessibility: the list is an \`<ol>\`, so screen readers announce the position. The current step has \`aria-current="step"\`. The status is not only shown by colour and icon: every heading starts with a visually hidden status text (\`Afgerond:\`, \`Huidige stap:\`, \`Nog niet gestart:\`). Markers and connector lines are \`aria-hidden\`.`;

