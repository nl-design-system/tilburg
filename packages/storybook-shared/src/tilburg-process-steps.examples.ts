type Status = 'checked' | 'current' | 'not-checked';
interface SubStep {
  title: string;
  status?: Status;
  date?: string;
}
interface Step extends SubStep {
  marker?: string;
  meta?: string;
  steps?: SubStep[];
}

const LABELS: Record<Status, string> = {
  checked: 'Afgerond',
  current: 'Huidige stap',
  'not-checked': 'Nog niet gestart',
};

export const checkIcon =
  '<svg class="denhaag-icon" aria-hidden="true" focusable="false" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><polyline points="20 6 9 17 4 12"></polyline></svg>';

const line = (status: Status, next?: Status): Status => (!next || next === 'not-checked' ? 'not-checked' : status);
const connector = (appearance: Status, from: string, to: string) =>
  `<div class="denhaag-step-marker__connector denhaag-step-marker__connector--${appearance} denhaag-step-marker__connector--${from}-to-${to}" aria-hidden="true"></div>`;
const hidden = (status: Status) => `<span class="utrecht-visually-hidden">${LABELS[status]}: </span>`;

/** The static reference DOM for a list of steps. */
const processStepsHtml = (steps: Step[]): string => {
  const items = steps.map((step, index) => {
    const status = step.status ?? 'not-checked';
    const next = steps[index + 1];
    const subSteps = step.steps ?? [];
    const body = [
      (next || subSteps.length > 0) &&
        connector(
          line(status, subSteps.length ? (subSteps[0].status ?? 'not-checked') : (next?.status ?? 'not-checked')),
          'main',
          subSteps.length ? 'nested' : 'main',
        ),
      step.meta && `<div class="denhaag-process-steps__step-meta">${step.meta}</div>`,
      step.date &&
        `<div class="denhaag-process-steps__step-meta denhaag-process-steps__step-meta--date">${step.date}</div>`,
    ]
      .filter(Boolean)
      .join('\n      ');
    const subItems = subSteps.map((sub, subIndex) => {
      const subStatus = sub.status ?? 'not-checked';
      const nextSub = subSteps[subIndex + 1];
      return `<li class="denhaag-process-steps__sub-step denhaag-process-steps__sub-step--${subStatus}">
            <div class="denhaag-process-steps__step-header denhaag-process-steps__step-header--nested">
              <div class="denhaag-step-marker denhaag-step-marker--${subStatus} denhaag-step-marker--nested" aria-hidden="true">${subStatus === 'checked' ? checkIcon : ''}</div>
              <p class="denhaag-process-steps__sub-step-heading">${hidden(subStatus)}${sub.title}</p>
            </div>${
              nextSub || next
                ? `\n            ${connector(line(subStatus, nextSub ? (nextSub.status ?? 'not-checked') : (next?.status ?? 'not-checked')), 'nested', nextSub ? 'nested' : 'main')}`
                : ''
            }${sub.date ? `\n            <div class="denhaag-process-steps__step-meta denhaag-process-steps__step-meta--nested">${sub.date}</div>` : ''}
          </li>`;
    });
    return `<li class="denhaag-process-steps__step denhaag-process-steps__step--${status}"${status === 'current' ? ' aria-current="step"' : ''}>
    <div class="denhaag-process-steps__step-header">
      <div class="denhaag-step-marker denhaag-step-marker--${status}" aria-hidden="true">${status === 'checked' ? checkIcon : (step.marker ?? String(index + 1))}</div>
      <p class="denhaag-process-steps__step-heading denhaag-process-steps__step-heading--${status}">${hidden(status)}${step.title}</p>
    </div>
    <div class="denhaag-process-steps__step-body">${body ? `\n      ${body}\n    ` : ''}</div>${
      subItems.length
        ? `\n    <div class="denhaag-process-steps__step-details">\n      <ol class="denhaag-process-steps">\n          ${subItems.join('\n          ')}\n      </ol>\n    </div>`
        : ''
    }
  </li>`;
  });
  return `<ol class="denhaag-process-steps">
  ${items.join('\n  ')}
</ol>`;
};

